/** Consumers may provide a static object or a Signal (for live language switching). */
export type AgtLabelsInput = AgtLabels | Signal<AgtLabels>;

export const AGT_LABELS = new InjectionToken<AgtLabelsInput>('AGT_LABELS', {
  factory: () => AGT_DEFAULT_LABELS,
});

/**
 * Normalized reactive view over {@link AGT_LABELS} — components call
 * `labels = injectLabels()` and read `labels().plan.statuses.done`.
 */
export function injectLabels(): Signal<AgtLabels> {
  const provided = inject(AGT_LABELS);
  return isSignal(provided) ? provided : computed(() => provided);
}
